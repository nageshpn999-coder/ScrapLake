const Lang = {
  current: localStorage.getItem("sl_lang") || "en",
  t(key) {
    const pack = I18N[this.current] || I18N.en;
    return pack[key] ?? I18N.en[key] ?? key;
  },
  set(lang) {
    this.current = I18N[lang] ? lang : "en";
    localStorage.setItem("sl_lang", this.current);
    document.documentElement.lang = this.current;
    this.apply();
  },
  apply() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = this.t(el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.placeholder = this.t(el.dataset.i18nPh);
    });
    document.querySelectorAll(".lang-btn").forEach((b) => {
      b.classList.toggle("active", b.dataset.lang === this.current);
      b.setAttribute("aria-pressed", b.dataset.lang === this.current);
    });
  },
};
